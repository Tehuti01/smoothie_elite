    /// Returns a flat list of references to all presets in the library.
    pub fn all_presets(&self) -> Vec<&Preset> {
        let mut all = Vec::new();
        all.extend(&self.rock_legends);
        all.extend(&self.mj_pop);
        all.extend(&self.celestial);
        all.extend(&self.golden_brass);
        all.extend(&self.obsidian_bass);
        all.extend(&self.synthwave);
        all.extend(&self.vintage_analog);
        all
    }

    /// Searches for a preset by its exact name.
    pub fn get_by_name(&self, name: &str) -> Option<&Preset> {
        self.all_presets().into_iter().find(|p| p.name == name)
    }

    /// Returns all presets belonging to a specific category.
    pub fn get_by_category(&self, category: &str) -> Vec<&Preset> {
        match category {
            "ROCK LEGENDS" => self.rock_legends.iter().collect(),
            "MJ POP ANTHOLOGY" => self.mj_pop.iter().collect(),
            "CELESTIAL CHOIRS" => self.celestial.iter().collect(),
            "GOLDEN BRASS" => self.golden_brass.iter().collect(),
            "OBSIDIAN BASS" => self.obsidian_bass.iter().collect(),
            "SYNTHWAVE 84" => self.synthwave.iter().collect(),
            "VINTAGE ANALOG" => self.vintage_analog.iter().collect(),
            _ => Vec::new(),
        }
    }
