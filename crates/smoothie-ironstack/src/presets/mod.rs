//! # Preset Management
//!
//! This module defines the structure of a DSP preset and provides an extensive
//! library of factory tones. Each preset contains parameters for the core engine
//! stages as well as a specific effects chain configuration.

use serde::{Deserialize, Serialize};

/// Represents a full engine state patch.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Preset {
    /// Distinctive name of the preset (e.g., "Back in Black").
    pub name: String,
    /// Broad category (e.g., "ROCK LEGENDS").
    pub category: String,
    /// A short description of the tone and intended use.
    pub description: String,
    /// Static parameters for the main engine stages.
    pub parameters: PresetParameters,
    /// Dynamic configuration for the modular effects chain.
    pub effects_chain: Vec<EffectConfig>,
}

/// Individual parameter values for a preset's engine stages.
/// All values are typically normalized between 0.0 and 1.0.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PresetParameters {
    pub volume: f32,
    pub pan: f32,
    pub drive: f32,
    pub glide: f32,
    pub attack: f32,
    pub decay: f32,
    pub sustain: f32,
    pub release: f32,
    pub cutoff: f32,
    pub res: f32,
    pub env: f32,
    pub drive2: f32,
    pub rev_decay: f32,
    pub rev_size: f32,
    pub rev_mix: f32,
    pub dly_time: f32,
    pub dly_feed: f32,
    pub dly_mix: f32,
}

/// Configuration for a specific effect module within a preset.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EffectConfig {
    /// Name of the effect module.
    pub name: String,
    /// Whether the effect is active by default.
    pub enabled: bool,
    /// Module-specific parameter overrides.
    pub parameters: std::collections::HashMap<String, f32>,
}

