use smoothie_core::math::FloatExt;
use smoothie_core::primitives::Sample;

/// An opaque, copy-able node identifier generated by the graph registry.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
/// Technical implementation of the NodeId structure.
pub struct NodeId(pub u32);

/// Technical implementation of the NodeConfig structure.
pub struct NodeConfig {
    pub sample_rate: f32,
    pub block_size: usize,
    pub channel_count: usize,
}

///
///
/// - `process()` allocates **zero** bytes on the heap.
/// - `process()` does not perform I/O, logging, or panicking.
pub trait AudioNode: Send {
    /// Human-readable name for debugging and UI display.
    fn name(&self) -> &'static str;

    /// Initialise the node with the host session configuration.
    fn init(&mut self, config: &NodeConfig);

    /// Reset all internal state (phase, history, envelopes) to zero.
    fn reset(&mut self);

    /// Process a single block of audio.
    ///
    /// - `inputs`  — slice of interleaved channel buffers feeding this node.
    /// - `outputs` — slice of interleaved channel buffers produced by this node.
    fn process(&mut self, inputs: &[&[Sample]], outputs: &mut [&mut [Sample]]);

    /// Number of audio input channels this node expects.
    fn input_channel_count(&self) -> usize {
        0
    }

    /// Number of audio output channels this node produces.
    fn output_channel_count(&self) -> usize {
        2
    }
}

